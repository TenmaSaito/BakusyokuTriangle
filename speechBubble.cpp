#include "object/game/player/speechBubble.h"

//==================================================================================
// --- 生成処理 ---
//==================================================================================
CSpeechBubble *CSpeechBubble::Create(const Vector3 &offset,
	const Vector2 &size)
{
	CSpeechBubble *pSpeechBubble = new CSpeechBubble;		// 生成したオブジェクト
	if (pSpeechBubble != nullptr && FAILED(pSpeechBubble->Init(offset, size)))
	{ // 生成成功 + 初期化失敗時、自動解放
		pSpeechBubble->Uninit();
		return nullptr;
	}

	return pSpeechBubble;
}

//==================================================================================
// --- コンストラクタ ---
//==================================================================================
CSpeechBubble::CSpeechBubble(const int nPriority) : CObjectBillboard3D(nPriority)
{ // タイプを指定
	SetType(TYPE::SPEECH_BUBBLE);
}

//==================================================================================
// --- デストラクタ ---
//==================================================================================
CSpeechBubble::~CSpeechBubble()
{
}

//==================================================================================
// --- 初期化処理 ---
//==================================================================================
HRESULT CSpeechBubble::Init(const Vector3 &offset,
	const Vector2 &size)
{ // 親クラスの初期化
	return CObjectBillboard3D::Init(offset, VECTOR3_NULL, size, INT_MAX);
}

//==================================================================================
// --- 終了処理 ---
//==================================================================================
void CSpeechBubble::Uninit(void)
{ // 親クラスの終了
	CObjectBillboard3D::Uninit();
}

//==================================================================================
// --- 更新処理 ---
//==================================================================================
void CSpeechBubble::Update(void)
{
}