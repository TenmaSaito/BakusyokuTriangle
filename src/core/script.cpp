#include "core/script.h"
#include "util/filestream.h"
#include "util/stringUtil.h"

//==================================================================================
// --- コンストラクタ ---
//==================================================================================
CScript::CScript()
{ // ファイルストリームのインスタンスを作成
	m_pFile = std::make_unique<CFileStream>();
}

//==================================================================================
// --- デストラクタ ---
//==================================================================================
CScript::~CScript()
{
}

//==================================================================================
// --- ファイルオープン処理 ---
//==================================================================================
bool CScript::Open(std::string_view path)
{ // ファイルを開く
	return m_pFile->Open(path, CFileStream::MODE::READ);
}

//==================================================================================
// --- ファイルクローズ処理 ---
//==================================================================================
void CScript::Close(void)
{ // ファイルを閉じる
	m_pFile->Close();
}

//==================================================================================
// --- コメント・タブスペースを消去した文字列の一列読み込み処理 ---
//==================================================================================
std::optional<std::string> CScript::ReadCleanLine(void)
{ // 文字列を一列読み込み、読み込めなかった場合は無効値を返す
	std::optional<std::string> line = m_pFile->ReadLine();
	if (line.has_value() == false) return std::nullopt;

	// コメント消去
	auto comment = line->find('#');
	if (comment != std::string::npos)
	{ // コメントが見つかった場合、そこから後ろを切り捨て
		line->erase(comment);
	}

	// タブスペース,スペース,改行を消去
	*line = StringUtil::Trim(*line, " \t\n");
	return line;
}