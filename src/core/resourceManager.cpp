#include "core/resourceManager.h"
#include "core/resourceable.h"
#include "render/texture.h"
#include "render/shader.h"
#include "render/xfile.h"

//==================================================================================
// === コンストラクタ ===
//==================================================================================
CResourceManager::CResourceManager()
{ // 各リソース管理クラスを取得
	m_vpResource.push_back(CTexture::GetInstance());
	m_vpResource.push_back(CShader::GetInstance());
	m_vpResource.push_back(CXFile::GetInstance());
}

//==================================================================================
// === デストラクタ ===
//==================================================================================
CResourceManager::~CResourceManager()
{
}

//==================================================================================
// === 一括読み込み処理 ===
//==================================================================================
void CResourceManager::LoadAll(void)
{
	for (auto &pResource : m_vpResource)
	{ // コンストラクタで登録済みのリソース管理クラスの読み込み処理を実行
		if (pResource == nullptr) continue;
		pResource->Load();
	}
}

//==================================================================================
// === 一括破棄処理 ===
//==================================================================================
void CResourceManager::UnloadAll(void)
{
	for (auto &pResource : m_vpResource)
	{ // コンストラクタで登録済みのリソース管理クラスの破棄処理を実行
		if (pResource == nullptr) continue;
		pResource->Unload();
	}
}