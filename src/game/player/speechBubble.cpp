#include "game/player/speechBubble.h"

//==================================================================================
// --- 生成処理 ---
//==================================================================================
CSpeechBubble *CSpeechBubble::Create(const Vector3 &offset,
	const Vector2 &size)
{
	CSpeechBubble *pSpeech = new CSpeechBubble;
	if (pSpeech != nullptr && FAILED(pSpeech->Init(offset, size)))
	{ // 吹き出し初期化失敗時、nullを返す
		pSpeech->Uninit();
		return nullptr;
	}

	return pSpeech;
}

//==================================================================================
// --- コンストラクタ ---
//==================================================================================
CSpeechBubble::CSpeechBubble(const int nPriority) : CObjectBillboard3D(nPriority)
{ // タイプ指定
	SetType(TYPE::SPEECH_BUBBLE);
}

//==================================================================================
// --- デストラクタ ---
//==================================================================================
CSpeechBubble::~CSpeechBubble()
{
}

